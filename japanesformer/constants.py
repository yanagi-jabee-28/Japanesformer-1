# -*- coding: utf-8 -*-

# 各母音（あ・い・う・え・お）の文字グループ定義
# 清音、濁音、半濁音を含み、全単射（可逆変換）の基準となる順序で並んでいます。
VOWEL_GROUPS = {
    "a": ["あ", "か", "さ", "た", "な", "は", "ま", "や", "ら", "わ", "が", "ざ", "だ", "ば", "ぱ"],
    "i": ["い", "き", "し", "ち", "に", "ひ", "み", "り", "ぎ", "じ", "ぢ", "び", "ぴ"],
    "u": ["う", "く", "す", "つ", "ぬ", "ふ", "む", "ゆ", "る", "ぐ", "ず", "づ", "ぶ", "ぷ"],
    "e": ["え", "け", "せ", "て", "ね", "へ", "め", "れ", "げ", "ぜ", "で", "べ", "ぺ"],
    "o": ["お", "こ", "そ", "と", "の", "ほ", "も", "よ", "ろ", "を", "ご", "ぞ", "ど", "ぼ", "ぽ"]
}

# 変換を行わず、そのまま透過させる特殊文字（促音、撥音、長音、小書き拗音、小書き母音）
SPECIAL_CHARS = set("っんーゃゅょぁぃぅぇぉ")

# O(1) で文字から母音グループ名とグループ内インデックスを特定するための逆引きテーブル
# インポート時に一度だけ事前構築されます。
CHAR_TO_GROUP = {}
for vowel, chars in VOWEL_GROUPS.items():
    for index, char in enumerate(chars):
        CHAR_TO_GROUP[char] = (vowel, index)
